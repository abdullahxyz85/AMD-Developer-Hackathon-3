"""
ingest.py — Knowledge base builder (Work Plan task 1.6)

Builds the retrieval index from both knowledge layers:
  Layer A  fact cards   (generated by scripts/load_games.py from games.json)
  Layer B  curated rules (knowledge/curated_rules/*.json)

Outputs (git-ignored, rebuildable):
  knowledge/index/chroma/   — Chroma PersistentClient DB (dense vectors)
  knowledge/index/bm25.pkl  — BM25Okapi index + aligned chunk list (keyword)

The chunk schema is shared with retrieval.py:
    { id, game, section, mechanic, layer, text, bgg_id, source{title,url} }

Usage:
    python3 scripts/ingest.py                    # full rebuild
    python3 scripts/ingest.py --dry-run          # show counts, write nothing
    python3 scripts/ingest.py --embed-model X    # override embedding model
"""

from __future__ import annotations

import argparse
import json
import pickle
import re
import sys
from pathlib import Path

# RAG/scripts/ -> RAG/
RAG_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(RAG_DIR / "scripts"))

from load_games import DEFAULT_INPUT, build_fact_cards, load_catalog  # noqa: E402

CURATED_DIR = RAG_DIR / "knowledge" / "curated_rules"
INDEX_DIR = RAG_DIR / "knowledge" / "index"
CHROMA_DIR = INDEX_DIR / "chroma"
BM25_PATH = INDEX_DIR / "bm25.pkl"
CHUNKS_PATH = INDEX_DIR / "chunks.json"

COLLECTION_NAME = "game_knowledge"
DEFAULT_EMBED_MODEL = "sentence-transformers/all-MiniLM-L6-v2"


def load_curated_chunks() -> list[dict]:
    """Convert curated rule files into chunks with the shared schema."""
    chunks: list[dict] = []
    for path in sorted(CURATED_DIR.glob("*.json")):
        data = json.load(open(path, encoding="utf-8"))
        game = data["game"]
        source_default = {"title": f"{game} — BoardGameGeek", "url": ""}
        for sec in data["sections"]:
            src = sec.get("source") or source_default
            chunks.append({
                "id": f"{game}:rule:{sec['section']}",
                "game": game,
                "section": sec["section"],
                "mechanic": None,
                "layer": "curated_rules",
                "text": f"{game} — {sec['section'].replace('_', ' ')}: {sec['text'].strip()}",
                "bgg_id": data.get("bgg_id"),
                "source": src,
            })
    return chunks


_TOKEN_RE = re.compile(r"[a-z0-9]+")


def tokenize(text: str) -> list[str]:
    """Simple tokenizer shared with the BM25 query side (retrieval.py)."""
    return _TOKEN_RE.findall(text.lower())


def build_all_chunks() -> list[dict]:
    """Fact cards (Layer A) + curated rules (Layer B), deduplicated by id."""
    data = load_catalog(DEFAULT_INPUT)
    fact_chunks = build_fact_cards(data)
    curated_chunks = load_curated_chunks()
    all_chunks = curated_chunks + fact_chunks  # curated first: higher authority
    seen: set[str] = set()
    unique: list[dict] = []
    for c in all_chunks:
        if c["id"] in seen:
            raise ValueError(f"duplicate chunk id: {c['id']}")
        seen.add(c["id"])
        unique.append(c)
    return unique


def main() -> None:
    ap = argparse.ArgumentParser(description="Build Chroma + BM25 knowledge index")
    ap.add_argument("--dry-run", action="store_true", help="report counts only")
    ap.add_argument("--embed-model", default=DEFAULT_EMBED_MODEL)
    ap.add_argument("--rebuild", action="store_true", default=True,
                    help="wipe and rebuild the index (default)")
    args = ap.parse_args()

    chunks = build_all_chunks()
    by_layer = {"curated_rules": 0, "fact_card": 0}
    for c in chunks:
        by_layer[c["layer"]] = by_layer.get(c["layer"], 0) + 1
    games = sorted({c["game"] for c in chunks})
    print(f"Chunks        : {len(chunks)}  {by_layer}")
    print(f"Games         : {len(games)}  {games}")
    print(f"Embed model   : {args.embed_model}")
    if args.dry_run:
        print("[DRY RUN] no index written")
        return

    INDEX_DIR.mkdir(parents=True, exist_ok=True)

    # --- Chroma (dense vectors) ---
    import chromadb

    client = chromadb.PersistentClient(path=str(CHROMA_DIR))
    try:
        client.delete_collection(COLLECTION_NAME)
    except Exception:
        pass  # first run: collection doesn't exist yet
    collection = client.create_collection(
        COLLECTION_NAME, metadata={"hnsw:space": "cosine"}
    )

    from sentence_transformers import SentenceTransformer

    print("Loading embedding model (first run downloads ~90 MB)...")
    model = SentenceTransformer(args.embed_model)
    texts = [c["text"] for c in chunks]
    print(f"Embedding {len(texts)} chunks...")
    embeddings = model.encode(texts, batch_size=64, show_progress_bar=False,
                              normalize_embeddings=True)

    collection.add(
        ids=[c["id"] for c in chunks],
        documents=texts,
        embeddings=[e.tolist() for e in embeddings],
        metadatas=[{
            "game": c["game"],
            "section": c["section"],
            "mechanic": c["mechanic"] or "",
            "layer": c["layer"],
            "source_title": c["source"]["title"],
            "source_url": c["source"]["url"],
            "bgg_id": c["bgg_id"] if c["bgg_id"] is not None else -1,
        } for c in chunks],
    )

    # --- BM25 (keyword) ---
    from rank_bm25 import BM25Okapi

    print("Building BM25 index...")
    bm25 = BM25Okapi([tokenize(t) for t in texts])
    with open(BM25_PATH, "wb") as f:
        pickle.dump({"ids": [c["id"] for c in chunks], "bm25": bm25}, f)

    # --- canonical chunk store (retrieval looks up text/metadata by id) ---
    with open(CHUNKS_PATH, "w", encoding="utf-8") as f:
        json.dump({"chunks": chunks, "embed_model": args.embed_model}, f,
                  ensure_ascii=False, indent=2)

    print(f"Chroma DB     : {CHROMA_DIR}  ({collection.count()} vectors)")
    print(f"BM25 index    : {BM25_PATH}")
    print(f"Chunk store   : {CHUNKS_PATH}")
    print("[OK] ingest complete")


if __name__ == "__main__":
    main()
